from functools import cached_property

import numpy as np


class Data:
    def __init__(self, id_: int, Fe: float, O2: float, pH: float | int, data: np.ndarray):
        self.id_ = id_
        self.Fe = Fe  # g/L
        self.O2 = O2  # atm
        self.pH = pH
        self.data = data  # mM

    def __str__(self):
        return f"{self.id_}-pH{self.pH:0.0f}-Fe{str(self.Fe).replace('.','_')}_O{str(self.O2).replace('.','_')}"

    def __len__(self):
        return len(self.time)

    def __eq__(self, other) -> bool:
        if isinstance(other, Data):
            if self.Fe == other.Fe and self.O2 == other.O2 and self.pH == other.pH:
                return True
        return False

    @cached_property
    def time(self) -> np.ndarray:
        return self.data[:, 0] * 60  # sec

    @cached_property
    def TEMPOH2_p(self) -> np.ndarray:
        return self.data[:, 1] / 1000  # M

    @cached_property
    def TEMPO(self) -> np.ndarray:
        return self.data[:, 2] / 1000  # M

    @cached_property
    def TEMPO_p(self) -> np.ndarray:
        return self.data[:, 3] / 1000  # M

    @cached_property
    def H(self) -> float:
        return 10 ** (-self.pH)  # M

    @cached_property
    def t_span(self) -> tuple[float, float]:
        return (np.min(self.time), np.max(self.time))


