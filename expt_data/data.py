def get_group_duplicate_datasets(data: list[Data]) -> list[list[int]]:
    included = np.zeros(len(data), dtype=bool)
    out = []
    for i in range(len(data)):
        sub_out = []
        if included[i]:
            continue
        sub_out.append(i)
        included[i] = True
        for j in range(i+1, len(data)):
            if data[i] == data[j]:
                included[j] = True
                sub_out.append(j)
        out.append(sub_out)

    return out


